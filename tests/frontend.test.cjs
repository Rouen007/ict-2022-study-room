function setup({boot, cache, failCache=false, saveHandler}={}) {
  const files = new Map(Object.entries(cache || {}));
  const nodes = {};
  const window = { nativeBoot: boot, webkit: saveHandler ? {messageHandlers:{saveNotebook:{postMessage:saveHandler}}} : undefined };
  const context = {window, console, setTimeout, clearTimeout, URL, Intl, Date, AbortController,
    localStorage:{getItem:k=>files.get(k)||null,setItem:(k,v)=>{if(failCache) throw Error('quota'); files.set(k,v);}},
    document:{getElementById:id=>nodes[id] || null}};
  vm.createContext(context);
  for(const file of ['library-data.js','course.js','distill-data.js']) vm.runInContext(fs.readFileSync(path.join(root,'study-room',file),'utf8'),context);
  const code=fs.readFileSync(path.join(root,'study-room/app.js'),'utf8').replace(/\ninit\(\);\s*$/, '');
  vm.runInContext(code,context);
  return {context,window,nodes,files,run:code=>vm.runInContext(code,context)};
}
